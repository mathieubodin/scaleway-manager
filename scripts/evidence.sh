#!/usr/bin/env bash
# Replay the checks and rewrite the whole evidence record of a work.
# Usage: scripts/evidence.sh <issue>. Writes _bmad-output/work/issue-<n>-*/evidence.md.
# Every check runs, even after a failure; the full output of each is kept, with
# colors removed and durations replaced by <t>, so that two runs on an unchanged
# tree differ only by their timestamp. Exit 1 when a check failed.
# See docs/development-process.md, "Evidence record".
set -euo pipefail

issue=${1:-}
[[ $issue =~ ^[1-9][0-9]*$ ]] || { echo "Error: issue must be a number, got '$issue'" >&2; exit 2; }

cd "$(git rev-parse --show-toplevel)"
shopt -s nullglob
dirs=(_bmad-output/work/issue-"$issue"-*/)
[ ${#dirs[@]} -eq 1 ] || { echo "Error: expected one _bmad-output/work/issue-$issue-*/ folder, found ${#dirs[@]}" >&2; exit 2; }
work=${dirs[0]%/}
out=$work/evidence.md

# Checks available today. #14 adds coverage and mutation testing, #15 the behavior diff.
checks=(lint-docs lint-workflows test-workflows check-frozen lint-go test-go check-go-mod lint-chart build-image "check-migration ISSUE=$issue")
not_run=(
  "Coverage, mutation testing: no target yet (#14)"
  "Behavior diff: no target yet (#15)"
)

# Colors out; durations (a number standing alone, minutes included), make's
# recursion level and thread counts replaced, so that the record is the same
# from `make evidence`, the script itself, or another machine.
normalize() {
  sed -E \
    -e 's/\x1b\[[0-9;]*m//g' \
    -e 's/duration_ms [0-9.]+/duration_ms <t>/g' \
    -e 's/(^|[^[:alnum:]_.-])([0-9]+m)?[0-9]+([.,][0-9]+)? ?(ms|µs|s)\b/\1<t>/g' \
    -e 's/^make(\[[0-9]+\])?:/make:/' \
    -e 's/using [0-9]+ threads/using <n> threads/g'
}

tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
failed=0
for i in "${!checks[@]}"; do
  # shellcheck disable=SC2086 # a check is a target plus its variables
  if make --no-print-directory ${checks[$i]} >"$tmp/$i.raw" 2>&1; then
    echo 0 >"$tmp/$i.code"
  else
    echo $? >"$tmp/$i.code"
    failed=1
  fi
  normalize <"$tmp/$i.raw" >"$tmp/$i.out"
done

{
  echo "# Evidence record: issue #$issue"
  echo
  echo "Generated by \`make evidence ISSUE=$issue\`. Do not edit: the next run rewrites this file."
  echo
  echo "- Generated at: $(date -u +%Y-%m-%dT%H:%M:%SZ)"
  echo "- Branch: \`$(git rev-parse --abbrev-ref HEAD)\`"
  echo "- Commit: \`$(git rev-parse HEAD)\`"
  if [ -z "$(git status --porcelain -- . ":(exclude)$out")" ]; then
    echo "- Working tree: clean"
  else
    echo "- Working tree: uncommitted changes (seen by every check except check-migration, which reads commits only)"
  fi
  echo
  echo "## Checks"
  echo
  echo "| Check | Result | make exit code |"
  echo "| --- | --- | --- |"
  for i in "${!checks[@]}"; do
    code=$(cat "$tmp/$i.code")
    result=passed
    [ "$code" = 0 ] || result=failed
    echo "| \`make ${checks[$i]}\` | $result | $code |"
  done
  echo
  echo "Not run:"
  echo
  for n in "${not_run[@]}"; do echo "- $n"; done
  for i in "${!checks[@]}"; do
    echo
    echo "### \`make ${checks[$i]}\`"
    echo
    echo '````text'
    cat "$tmp/$i.out"
    echo '````'
  done
  echo
  echo "## Token cost"
  echo
  if [ -f "$work/cost.json" ] && jq -e '.totals.steps and .totals.models' "$work/cost.json" >/dev/null 2>&1; then
    jq -r '
      def tok: (.input // 0) + (.output // 0) + (.cacheCreation // 0);
      def sumcat($m): reduce ($m | to_entries[] | .value) as $v
        ({input: 0, output: 0, cacheCreation: 0, cacheRead: 0};
         .input += $v.input | .output += $v.output | .cacheCreation += $v.cacheCreation | .cacheRead += $v.cacheRead);
      def row($name; $t): "| \($name) | \($t.input) | \($t.output) | \($t.cacheCreation) | \($t.cacheRead) | \($t | tok) |";
      "From `cost.json` (route: \(.route // "none"); `Tokens` = input + output + cache creation, attributed steps only): **\(.tokens)**.",
      "",
      "| Step | Input | Output | Cache creation | Cache read | Tokens |",
      "| --- | --- | --- | --- | --- | --- |",
      (.totals.steps | to_entries[] | row(.key; sumcat(.value))),
      "",
      "| Model | Input | Output | Cache creation | Cache read | Tokens |",
      "| --- | --- | --- | --- | --- | --- |",
      (.totals.models | to_entries[] | row("`\(.key)`"; .value)),
      "",
      (if (.totals.unattributed | length) == 0 then "Unattributed: none."
       else "Unattributed (outside `Tokens`): \(sumcat(.totals.unattributed) | tok) tokens, \(sumcat(.totals.unattributed).cacheRead) cache reads." end)
    ' "$work/cost.json"
  elif [ -f "$work/cost.json" ]; then
    echo "\`$work/cost.json\` is not readable as written by \`make cost\`: run \`make cost ISSUE=$issue\` again."
  else
    echo "No \`cost.json\` in \`$work/\`: run \`make cost ISSUE=$issue\` first."
  fi
} >"$out"

echo "Wrote $out"
[ "$failed" = 0 ] || { echo "Error: at least one check failed, see $out"; exit 1; }
